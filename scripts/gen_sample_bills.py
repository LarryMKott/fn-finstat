def gen_wechat(path: Path) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "微信支付账单明细"
    ws.append(["微信支付账单明细"])
    ws.append(["微信昵称：[示例用户]"])
    ws.append(["起始时间：[2026-08-01 00:00:00] 终止时间：[2026-09-30 23:59:59]"])
    ws.append(["导出类型：全部"])
    ws.append(["----------------------微信支付账单明细---------------------"])
    ws.append(WECHAT_HEADER)
    for row in WECHAT_ROWS:
        ws.append(list(row))
    ws.append(["共%d笔" % len(WECHAT_ROWS)])
    wb.save(path)
    print(f"generated: {path}")


def gen_alipay(path: Path) -> None:
    buf = io.StringIO()
    buf.write("支付宝交易流水证明\r\n")
    buf.write("支付宝账户：sample@example.com\r\n")
    buf.write("起始日期：[2026-08-01 00:00:00]  终止日期：[2026-09-30 23:59:59]\r\n")
    buf.write("导出时间：[2026-10-01 10:00:00]\r\n")
    buf.write(
        "---------------------------------交易流水明细---------------------------------\r\n"
    )
    writer = csv.writer(buf)
    writer.writerow(ALIPAY_HEADER)
    for row in ALIPAY_ROWS:
        writer.writerow(list(row))
    buf.write(
        "---------------------------------交易流水明细---------------------------------\r\n"
    )
    path.write_bytes(buf.getvalue().encode("gb18030"))
    print(f"generated: {path}")


