def main() -> int:
    ok = fail = 0
    for merchant, remark, expected in CASES:
        got = detect_region(merchant, remark)
        city = detect_city(merchant, remark)
        if got == expected:
            ok += 1
            print(f"  OK   {merchant:<26} -> {got or '未识别'} / {city or '-'}")
        else:
            fail += 1
            print(
                f"  FAIL {merchant:<26} -> {got or '未识别'} (期望 {expected or '未识别'})"
                f" / city={city or '-'}"
            )
    total = ok + fail
    print(f"\n命中 {ok}/{total}，失败 {fail}")
    return 1 if fail else 0


