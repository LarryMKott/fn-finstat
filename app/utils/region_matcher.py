def _normalize_province(name: str) -> str:
    """省名归一化为与地图一致的全称；直辖市补「市」后缀"""
    if name in _PROVINCE_OUTPUT:
        return _PROVINCE_OUTPUT[name]
    if name in _MUNICIPALITIES:
        return name + "市"
    # 已是全称则直接返回
    if name.endswith(("省", "市", "自治区", "特别行政区")):
        return name
    return name + "省"


def _province_of(name: str) -> str | None:
    """城市名或省名 → 标准省级全称；两者都不匹配返回 None"""
    if name in _CITY_TO_PROVINCE:
        return _normalize_province(_CITY_TO_PROVINCE[name])
    if name in _PROVINCES:
        return _normalize_province(name)
    return None


def _city_candidates(text: str) -> list[tuple[int, str, str]]:
    """收集文本中的城市证据，返回 (证据强度, 城市名, 省级全称) 列表

    证据强度（越大越可靠）：
        3 —— 城市名带行政后缀全称，如「成都市」「乌鲁木齐市」：几乎不会误判
        2 —— 城市名裸词，如「成都」「杭州」：可能被「长安街」类词语误伤
    同强度时以**出现位置靠前**者胜出（商户名的前缀通常才是主体）。
    """
    found: list[tuple[int, str, str]] = []
    for city, province in _CITY_TO_PROVINCE.items():
        if city in _NEGATIVE:
            continue
        full = next(
            (city + s for s in _CITY_SUFFIXES if city + s in text),
            None,
        )
        if full:
            found.append((3, city, _normalize_province(province)))
        elif city in text:
            found.append((2, city, _normalize_province(province)))
    return found


def _best(candidates: list[tuple[int, int, str]]):
    """按 (证据强度, 出现位置) 择优：强度优先，同强度取最靠前的一条"""
    if not candidates:
        return None
    candidates.sort(key=lambda c: (-c[0], c[1]))
    return candidates[0][2]


def _resolve(text: str, province: bool):
    """城市证据与地标证据的仲裁：返回择优结果或 None

    关键规则：**城市名出现在地标之前时，城市名更可能是主体**。
    「海口国贸」= 海口的国贸（海口胜）、「成都春熙路店」= 成都的春熙路（成都胜）；
    反之「南京路步行街」里「南京」只是路名的一部分，应采信地标指向的上海。

    实现：地标位于城市名之后时降级到与城市裸词同级，让位置靠前者胜出。
    """
    cities = _city_candidates(text)
    landmarks: list[tuple[int, int, str, str]] = []
    for landmark, city in _LANDMARKS.items():
        pos = text.find(landmark)
        if pos < 0:
            continue
        prov = _CITY_TO_PROVINCE.get(city, city)
        landmarks.append(
            (pos, city, _normalize_province(prov) if province else city, landmark)
        )

    hits: list[tuple[int, int, str]] = []
    # 城市名带行政后缀（强度 3）与地标同级，裸词为强度 2；
    # 「城市在前则城市胜」的规则由下方地标的 covered 降级实现
    for strength, city, prov in cities:
        pos = text.find(city)
        value = prov if province else city
        hits.append((strength, pos, value))

    for pos, city, value, _lm in landmarks:
        covered = any(c_pos < pos for _s, c_pos, _v in hits)
        # 城市名已在前 → 地标是其附属描述，降级为 2 与新证据同级比较
        hits.append((2 if covered else 3, pos, value))

    return _best(hits)


def detect_region(*texts: str) -> str | None:
    """从若干文本片段（商户名、备注等）中识别省级行政区

    返回与 ECharts 中国地图一致的省级全称（如「四川省」「北京市」），
    无法判定时返回 None —— 调用方应将其归入「未识别」，不要伪造地域。

    判定顺序（先精确后宽泛）：
        1. 城市名 / 省名的行政全称（含「省」「市」「自治区」等后缀）
        2. 地标 / 商圈 / 路名与城市名（「南京路」→ 上海、「海口国贸」→ 海口）
        3. 省名裸词
    """
    text = " ".join(t for t in texts if t).strip()
    if not text:
        return None

    # 1) 带行政后缀的省 / 市全称：「成都市」「内蒙古自治区」「乌鲁木齐市」
    #    后缀按长度降序，保证「内蒙古自治区」不被「区」抢先截断
    hits: list[tuple[int, int, str]] = []
    for suffix in _ADMIN_SUFFIX:
        idx = text.find(suffix)
        while idx > 0:
            # 向前最多取 4 个字作为候选地名（覆盖「内蒙古自治区」「乌鲁木齐市」等）
            for span in (4, 3, 2):
                start = idx - span
                if start < 0:
                    continue
                resolved = _province_of(text[start:idx])
                if resolved:
                    hits.append((4, start, resolved))
                    break
            idx = text.find(suffix, idx + len(suffix))
    if hits:
        return _best(hits)

    # 2) 地标与城市名仲裁
    resolved = _resolve(text, province=True)
    if resolved:
        return resolved

    # 3) 省名裸词
    for prov_name in _PROVINCES:
        if prov_name in text:
            return _normalize_province(prov_name)

    return None


def detect_city(*texts: str) -> str | None:
    """识别城市名（用于「消费城市 TOP」与地图下钻）

    与 detect_region 同源，返回未经归一化的城市名（如「成都」「北京」），
    直辖市返回其本体名。无法判定返回 None。
    """
    text = " ".join(t for t in texts if t).strip()
    if not text:
        return None

    hits: list[tuple[int, int, str]] = []
    for suffix in _ADMIN_SUFFIX:
        idx = text.find(suffix)
        while idx > 0:
            for span in (4, 3, 2):
                start = idx - span
                if start < 0:
                    continue
                candidate = text[start:idx]
                if candidate in _CITY_TO_PROVINCE:
                    hits.append((4, start, candidate))
                    break
            idx = text.find(suffix, idx + len(suffix))
    if hits:
        return _best(hits)

    return _resolve(text, province=False)
