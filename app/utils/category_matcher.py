def match_category(merchant: str, remark: str = "") -> str:
    """按关键词匹配消费分类，未命中返回“其他”"""
    text = f"{merchant} {remark}".lower()
    for category, keywords in RULES.items():
        for kw in keywords:
            if kw.lower() in text:
                return category
    return "其他"
